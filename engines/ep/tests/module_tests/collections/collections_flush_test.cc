TEST_F(CollectionsVBFlushTest, dropDefaultCollectionEpoch) {
    dropCollection(1, ManifestUid{1}, CollectionMetaData{});
    commit();

    // Expects an empty open collections list and no dropped list
    expectDisk(
            {.manifestUid = ManifestUid{1}, .collections = OpenCollections{}});
}

// Drop and re-create (resurrect) a collection which is on disk. The new
// generation is open and the old generation is dropped.
TEST_F(CollectionsVBFlushTest, resurrectCollectionOnDisk) {
    createCollection(10, ManifestUid{1}, fruit);
    commit();

    auto fruit2 = fruit;
    fruit2.maxTtl = 5s;
    flushMutation(fruit.cid, 11);
    dropCollection(12, ManifestUid{2}, fruit);
    createCollection(13, ManifestUid{3}, fruit2);
    EXPECT_TRUE(flush->isOpen(fruit.cid));
    commit();

    // Expects the new fruit open from 13 and the old one dropped 10 to 12
    expectDisk({.manifestUid = ManifestUid{3},
                .collections = OpenCollections{defaultCollection, {13, fruit2}},
                .dropped = DroppedList{{10, 12, fruit.cid}}});
}

// Create, drop and create again in the same batch. Open is the last create and
// the dropped span starts from the first create.
TEST_F(CollectionsVBFlushTest, createDropCreateCollection) {
    auto fruit2 = fruit;
    fruit2.maxTtl = 5s;

    createCollection(1, ManifestUid{1}, fruit);
    flushMutation(fruit.cid, 2);
    dropCollection(3, ManifestUid{2}, fruit);
    createCollection(4, ManifestUid{3}, fruit2);
    commit();

    // Expects the second fruit open and the first one dropped 1 to 3
    expectDisk({.manifestUid = ManifestUid{3},
                .collections = OpenCollections{defaultCollection, {4, fruit2}},
                .dropped = DroppedList{{1, 3, fruit.cid}}});
}

// The dropped list on disk is merged with drops of the batch. A collection in
// both lists is encoded once, with the new endSeqno.
TEST_F(CollectionsVBFlushTest, droppedMergeWithDisk) {
    createCollection(1, ManifestUid{1}, fruit);
    createCollection(2, ManifestUid{2}, vegetable);
    createCollection(3, ManifestUid{3}, dairy);
    commit();
    // Baseline, three new collections
    expectDisk({.manifestUid = ManifestUid{3},
                .collections = OpenCollections{defaultCollection,
                                               {1, fruit},
                                               {2, vegetable},
                                               {3, dairy}}});

    flushMutation(fruit.cid, 4);
    flushMutation(vegetable.cid, 5);
    dropCollection(6, ManifestUid{4}, fruit);
    dropCollection(7, ManifestUid{5}, vegetable);
    commit();
    // fruit and vegetable now dropped, dairy still open
    expectDisk(
            {.manifestUid = ManifestUid{5},
             .collections = OpenCollections{defaultCollection, {3, dairy}},
             .dropped = DroppedList{{1, 6, fruit.cid}, {2, 7, vegetable.cid}}});

    // fruit (still in the dropped list) is resurrected and dropped again.
    // dairy is dropped for the first time.
    createCollection(8, ManifestUid{6}, fruit);
    flushMutation(fruit.cid, 9);
    flushMutation(dairy.cid, 10);
    dropCollection(11, ManifestUid{7}, fruit);
    dropCollection(12, ManifestUid{8}, dairy);
    commit();

    // fruit's entry keeps its original start but takes the new end,
    // vegetable is unchanged and dairy is added
    expectDisk({.manifestUid = ManifestUid{8},
                .collections = OpenCollections{defaultCollection},
                .dropped = DroppedList{{1, 11, fruit.cid},
                                       {2, 7, vegetable.cid},
                                       {3, 12, dairy.cid}}});
}

// A create event with a flushUid is a collection flush. The open collection
// takes the new flushUid and the old items are recorded as dropped.
TEST_F(CollectionsVBFlushTest, flushCollection) {
    createCollection(10, ManifestUid{1}, fruit);
    commit();

    const auto flushed = flushCollection(20, ManifestUid{7}, fruit);
    commit();

    // Expects fruit open with the new flushUid and the old items dropped
    // Note: the dropped entry of a flushed collection currently has a
    // startSeqno of 0
    expectDisk(
            {.manifestUid = ManifestUid{7},
             .collections = OpenCollections{defaultCollection, {20, flushed}},
             .dropped = DroppedList{{0, 20, fruit.cid}}});
}

// A create of a collection which is already on disk (and is not a flush) is a
