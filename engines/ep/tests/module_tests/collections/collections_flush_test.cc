using namespace std::chrono_literals;
using Collections::CollectionMetaData;
using Collections::ManifestUid;
using Collections::ScopeMetaData;
using Collections::KVStore::DroppedCollection;
using Collections::KVStore::OpenCollection;
using Collections::KVStore::OpenScope;
using ::testing::UnorderedElementsAre;
using ::testing::UnorderedElementsAreArray;
using SystemEventType = Collections::VB::Manifest::SystemEventType;
using OpenCollections = std::vector<OpenCollection>;
using OpenScopes = std::vector<OpenScope>;
using DroppedList = std::vector<DroppedCollection>;

class CollectionsVBFlushTest : public ::testing::Test {
protected:
    CollectionsVBFlushTest() {
        newBatch();
    }

    /**
     * Create a collection system event at the given seqno.
     */
    static std::unique_ptr<Item> makeCollectionEvent(
            uint64_t seqno,
            ManifestUid uid,
            const CollectionMetaData& meta,
            SystemEventType type = SystemEventType::Begin) {
        Collections::VB::ManifestEntry entry(
                make_STRCPtr<Collections::VB::CollectionSharedMetaData>(
                        meta.name, meta.sid),
                seqno,
                meta.canDeduplicate,
                meta.maxTtl,
                meta.metered,
                meta.flushUid);
        return Collections::VB::Manifest::makeCollectionSystemEvent(
                uid, meta.cid, meta.name, entry, type, int64_t(seqno));
    }

    /**
     * Record a create collection event in the current batch.
     */
    void createCollection(uint64_t seqno,
                          ManifestUid uid,
                          const CollectionMetaData& meta) {
        flush->recordSystemEvent(*makeCollectionEvent(seqno, uid, meta));
    }

    /**
     * Record a flush collection event in the current batch, a create event
     * with the flush's manifest uid as the flushUid.
     * @return the collection's metadata after the flush
     */
    CollectionMetaData flushCollection(uint64_t seqno,
                                       ManifestUid uid,
                                       CollectionMetaData meta) {
        meta.flushUid = uid;
        createCollection(seqno, uid, meta);
        return meta;
    }

    /**
     * Record a modify collection event in the current batch.
     */
    void modifyCollection(uint64_t seqno,
                          ManifestUid uid,
                          const CollectionMetaData& meta) {
        flush->recordSystemEvent(*makeCollectionEvent(
                seqno, uid, meta, SystemEventType::Modify));
    }

    /**
     * Record a drop collection event in the current batch.
     */
    void dropCollection(uint64_t seqno,
                        ManifestUid uid,
                        const CollectionMetaData& meta) {
        flush->recordSystemEvent(
                *makeCollectionEvent(seqno, uid, meta, SystemEventType::End));
    }

    /**
     * Record a create scope event in the current batch.
     */
    void createScope(uint64_t seqno,
                     ManifestUid uid,
                     const ScopeMetaData& meta) {
        flush->recordSystemEvent(
                *Collections::VB::Manifest::makeCreateScopeSystemEvent(
                        uid, meta.sid, meta.name, int64_t(seqno)));
    }

    /**
     * Record a drop scope event in the current batch.
     */
    void dropScope(uint64_t seqno, ManifestUid uid, ScopeID sid) {
        flush->recordSystemEvent(
                *Collections::VB::Manifest::makeDropScopeSystemEvent(
                        uid, sid, false /*isSystemScope*/, int64_t(seqno)));
    }

    /**
     * Account for a committed mutation in the given collection. When the
     * collection is dropped in the same batch, this marks the collection as
     * non-empty, so Flush does not need to consult the VB::Manifest.
     */
    void flushMutation(CollectionID cid, uint64_t seqno) {
        StoredDocKey key{"key", cid};
        flush->updateStats(
                key, seqno, IsCommitted::Yes, IsDeleted::No, 100 /*size*/);
    }

    /**
     * Begin a new flush batch, the Flush is given the dropped collections
     * from "disk" as a KVStore would.
     */
    void newBatch() {
        flush.emplace(manifest);
        flush->setDroppedCollectionsForStore(getDiskDropped());
    }

    /**
     * Commit the current batch. As a KVStore does, each item of metadata is
     * re-encoded only if the batch changed it and using the current disk
     * state as input. The encoded output becomes the new disk state and a new
     * batch begins.
     */
    void commit() {
        if (flush->getManifestUid() != ManifestUid{0}) {
            disk.manifestUid = flush->encodeManifestUid();
        }

        if (flush->isOpenCollectionsChanged()) {
            disk.collections =
                    flush->encodeOpenCollections(view(disk.collections));
        }

        if (flush->isDroppedCollectionsChanged() ||
            flush->isDroppedStatsChanged()) {
            auto dropped = getDiskDropped();
            auto buf = flush->encodeDroppedCollections(dropped);
            // An empty buffer means nothing to store, disk is unchanged.
            if (buf.data()) {
                disk.dropped = std::move(buf);
            }
        }

        if (flush->isScopesChanged()) {
            disk.scopes = flush->encodeOpenScopes(view(disk.scopes));
        }

        newBatch();
    }

    static cb::const_byte_buffer view(const flatbuffers::DetachedBuffer& buf) {
        return {buf.data(), buf.size()};
    }

    std::vector<DroppedCollection> getDiskDropped() const {
        return Collections::KVStore::decodeDroppedCollections(
                view(disk.dropped));
    }

    /**
     * The expected state of all of the metadata on "disk". A std::nullopt
     * member means that the document must never have been written.
     */
    struct ExpectedDisk {
        std::optional<ManifestUid> manifestUid = std::nullopt;
        std::optional<std::vector<OpenCollection>> collections = std::nullopt;
        std::optional<std::vector<OpenScope>> scopes = std::nullopt;
        std::optional<std::vector<DroppedCollection>> dropped = std::nullopt;
    };

    /**
     * Check all of the metadata on "disk" matches expected.
     */
    void expectDisk(const ExpectedDisk& expected,
                    std::source_location location =
                            std::source_location::current()) const {
        ::testing::ScopedTrace trace(
                location.file_name(), int(location.line()), "expectDisk");

        if (expected.manifestUid) {
            ASSERT_NE(0, disk.manifestUid.size()) << "manifestUid not written";
            EXPECT_EQ(*expected.manifestUid,
                      Collections::KVStore::decodeManifestUid(
                              view(disk.manifestUid)));
        } else {
            EXPECT_EQ(0, disk.manifestUid.size())
                    << "manifestUid unexpectedly written";
        }

        if (expected.collections) {
            ASSERT_NE(0, disk.collections.size()) << "collections not written";
            EXPECT_THAT(Collections::KVStore::decodeOpenCollections(
                                view(disk.collections)),
                        UnorderedElementsAreArray(*expected.collections));
        } else {
            EXPECT_EQ(0, disk.collections.size())
                    << "collections unexpectedly written";
        }

        if (expected.scopes) {
            ASSERT_NE(0, disk.scopes.size()) << "scopes not written";
            EXPECT_THAT(Collections::KVStore::decodeManifest(
                                {}, {}, view(disk.scopes), {})
                                .scopes,
                        UnorderedElementsAreArray(*expected.scopes));
        } else {
            EXPECT_EQ(0, disk.scopes.size()) << "scopes unexpectedly written";
        }

        if (expected.dropped) {
            ASSERT_NE(0, disk.dropped.size()) << "dropped not written";
            EXPECT_THAT(getDiskDropped(),
                        UnorderedElementsAreArray(*expected.dropped));
        } else {
            EXPECT_EQ(0, disk.dropped.size()) << "dropped unexpectedly written";
        }
    }

    /** The state of the default collection when nothing is on disk */
    const OpenCollection defaultCollection{0, CollectionMetaData{}};
    /** The state of the default scope when nothing is on disk */
    const OpenScope defaultScope{0, ScopeMetaData{}};

    const CollectionMetaData fruit{ScopeID{8},
                                   CollectionID{8},
                                   "fruit",
                                   cb::NoExpiryLimit,
                                   CanDeduplicate::Yes,
                                   Collections::Metered::No,
                                   ManifestUid{}};
    const CollectionMetaData dairy{ScopeID{9},
                                   CollectionID{9},
                                   "dairy",
                                   cb::ExpiryLimit{100s},
                                   CanDeduplicate::No,
                                   Collections::Metered::Yes,
                                   ManifestUid{}};
    const CollectionMetaData vegetable{ScopeID{9},
                                       CollectionID{10},
                                       "vegetable",
                                       cb::NoExpiryLimit,
                                       CanDeduplicate::Yes,
                                       Collections::Metered::No,
                                       ManifestUid{}};
    const ScopeMetaData shop1{ScopeID{8}, "shop1"};
    const ScopeMetaData shop2{ScopeID{9}, "shop2"};

    Collections::VB::Manifest manifest{
            std::make_shared<Collections::Manager>()};

    /** The current flush batch */
    std::optional<Collections::VB::Flush> flush;

    /** The metadata as a KVStore would have stored it */
    struct {
        flatbuffers::DetachedBuffer manifestUid;
        flatbuffers::DetachedBuffer collections;
        flatbuffers::DetachedBuffer scopes;
        flatbuffers::DetachedBuffer dropped;
    } disk;
};

// The greatest uid of all events in the batch is encoded
TEST_F(CollectionsVBFlushTest, manifestUid) {
    createCollection(1, ManifestUid{5}, fruit);
    createScope(2, ManifestUid{3}, shop1);
    commit();
    // Highest uid (5) wins, collection and scope both written
    expectDisk({.manifestUid = ManifestUid{5},
                .collections = OpenCollections{defaultCollection, {1, fruit}},
                .scopes = OpenScopes{defaultScope, {2, shop1}}});

    flushMutation(fruit.cid, 3);
    dropCollection(4, ManifestUid{7}, fruit);
    createScope(5, ManifestUid{6}, shop2);
    commit();
    // Uid moves on to 7, fruit is now dropped and shop2 added
    expectDisk({.manifestUid = ManifestUid{7},
                .collections = OpenCollections{defaultCollection},
                .scopes = OpenScopes{defaultScope, {2, shop1}, {5, shop2}},
                .dropped = DroppedList{{1, 4, fruit.cid}}});
}

// A batch with no system events (e.g. just mutations) writes no metadata
TEST_F(CollectionsVBFlushTest, noSystemEvents) {
    flushMutation(CollectionID::Default, 1);
    commit();
    // No metadata should have been written at all
    expectDisk({});
}

// Nothing on disk, create collections. All metadata fields must be encoded and
// the default collection is assumed to exist.
TEST_F(CollectionsVBFlushTest, createCollectionNothingOnDisk) {
    createCollection(1, ManifestUid{1}, fruit);
    createCollection(2, ManifestUid{2}, dairy);
    EXPECT_TRUE(flush->isReadyForCommit());
    commit();

    // Expects the default collection and the newly created collections
    expectDisk({.manifestUid = ManifestUid{2},
                .collections = OpenCollections{
                        defaultCollection, {1, fruit}, {2, dairy}}});
}

// Collections on disk are merged with those created in the batch, the on disk
// state is preserved.
TEST_F(CollectionsVBFlushTest, createCollectionMergeWithDisk) {
    createCollection(10, ManifestUid{1}, dairy);
    commit();
    createCollection(11, ManifestUid{2}, fruit);
    commit();

    // Expects dairy from disk plus fruit from this batch
    expectDisk({.manifestUid = ManifestUid{2},
                .collections = OpenCollections{
                        defaultCollection, {10, dairy}, {11, fruit}}});
}

// The default collection is only assumed when nothing is on disk. Once dropped
// it is not resurrected by a later batch.
TEST_F(CollectionsVBFlushTest, createCollectionAfterDefaultDropped) {
    // drop the default collection
    dropCollection(1, ManifestUid{1}, CollectionMetaData{});
    createCollection(10, ManifestUid{1}, dairy);
    commit();
    // Default is dropped, but was empty so isn't in the dropped list
    expectDisk({.manifestUid = ManifestUid{1},
                .collections = OpenCollections{{10, dairy}}});

    createCollection(11, ManifestUid{2}, fruit);
    commit();
    // Default stays dropped, fruit is added alongside dairy
    expectDisk({.manifestUid = ManifestUid{2},
                .collections = OpenCollections{{10, dairy}, {11, fruit}}});
}

// The same collection created twice in a batch (e.g. replica receiving
// create/drop/create, flushed without the drop). The highest seqno create
// is encoded, regardless of the order the events are recorded.
TEST_F(CollectionsVBFlushTest, createCollectionTwice) {
    auto fruit2 = fruit;
    fruit2.maxTtl = 50s;
    createCollection(5, ManifestUid{2}, fruit2);
    createCollection(1, ManifestUid{1}, fruit);
    commit();

    // Expects only the seqno 5 generation of fruit
    expectDisk(
            {.manifestUid = ManifestUid{2},
             .collections = OpenCollections{defaultCollection, {5, fruit2}}});
}

// A create and modify in the same batch, the modified metadata is encoded but
// the startSeqno is that of the create.
TEST_F(CollectionsVBFlushTest, createAndModifyCollection) {
    auto modified = fruit;
    modified.maxTtl = 99s;
    modified.canDeduplicate = CanDeduplicate::No;
    modified.metered = Collections::Metered::Yes;

    createCollection(1, ManifestUid{1}, fruit);
    modifyCollection(2, ManifestUid{2}, modified);
    commit();

    // Expects fruit with the modified metadata, but still starting at seqno 1
    expectDisk(
            {.manifestUid = ManifestUid{2},
             .collections = OpenCollections{defaultCollection, {1, modified}}});
}

// Many modifications in one batch, the highest seqno modification wins.
TEST_F(CollectionsVBFlushTest, modifyCollectionMany) {
    auto modified1 = fruit;
    modified1.maxTtl = 1s;
    auto modified2 = fruit;
    modified2.maxTtl = 2s;

    createCollection(1, ManifestUid{1}, fruit);
    modifyCollection(3, ManifestUid{3}, modified2);
    modifyCollection(2, ManifestUid{2}, modified1);
    commit();

    // Expects the seqno 3 modification, not the seqno 2 one
    expectDisk({.manifestUid = ManifestUid{3},
                .collections =
                        OpenCollections{defaultCollection, {1, modified2}}});
}

// A modification which precedes the create (create is a resurrection) must not
// be applied to the newer generation of the collection.
TEST_F(CollectionsVBFlushTest, modifyBeforeCreateIgnored) {
    auto modified = fruit;
    modified.maxTtl = 99s;
    modifyCollection(1, ManifestUid{1}, modified);
    createCollection(2, ManifestUid{2}, fruit);
    commit();

    // Expects fruit as created, the earlier modify is ignored
    expectDisk({.manifestUid = ManifestUid{2},
                .collections = OpenCollections{defaultCollection, {2, fruit}}});
}

