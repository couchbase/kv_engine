/**
 * Unit tests for Collections::VB::Flush which check the FlatBuffers metadata
 * that Flush generates (and which a KVStore will persist) without involving
 * any KVStore.
 *
 * System events are created with the VB::Manifest event generators at seqnos
 * chosen by each test. Each test runs one or more flush batches, at the end of
 * each batch commit() encodes the metadata as a KVStore would, using the
 * output of the previous batch as the current "disk" state. Thus all of the
 * disk state is generated by Flush itself.
 */

