// Compaction uses encodeRelativeComplementOfDroppedCollections to remove
// purged collections from the dropped list which flush generated.
TEST_F(CollectionsVBFlushTest, encodeRelativeComplementOfDroppedCollections) {
    createCollection(1, ManifestUid{1}, fruit);
    createCollection(2, ManifestUid{2}, dairy);
    createCollection(3, ManifestUid{3}, vegetable);
    commit();
    flushMutation(fruit.cid, 4);
    flushMutation(dairy.cid, 5);
    flushMutation(vegetable.cid, 6);
    dropCollection(7, ManifestUid{4}, fruit);
    dropCollection(8, ManifestUid{5}, dairy);
    dropCollection(9, ManifestUid{6}, vegetable);
    commit();
    // Baseline, all three collections in the dropped list
    expectDisk({.manifestUid = ManifestUid{6},
                .collections = OpenCollections{defaultCollection},
                .dropped = DroppedList{{1, 7, fruit.cid},
                                       {2, 8, dairy.cid},
                                       {3, 9, vegetable.cid}}});

    using Collections::VB::Flush;
    // fruit is removed. dairy is unknown to idsToRemove so remains. vegetable
    // was dropped after the given endSeqno so remains.
    auto buf = Flush::encodeRelativeComplementOfDroppedCollections(
            getDiskDropped(), {fruit.cid, vegetable.cid}, 8);
    EXPECT_THAT(Collections::KVStore::decodeDroppedCollections(view(buf)),
                UnorderedElementsAre(DroppedCollection{2, 8, dairy.cid},
                                     DroppedCollection{3, 9, vegetable.cid}));

    // Everything removed, the output is empty (no data)
    buf = Flush::encodeRelativeComplementOfDroppedCollections(
            getDiskDropped(), {fruit.cid, dairy.cid, vegetable.cid}, 9);
    EXPECT_EQ(0, buf.size());
}

/**
 * Tests which require a VB::Manifest which has processed the system events.
 * Some parts of Flush consult the VB::Manifest, e.g. to determine if a dropped
 * collection is empty.
 */
class CollectionsVBFlushManifestTest : public CollectionsVBFlushTest {
protected:
    class DummyCB : public Callback<Vbid> {
    public:
        void callback(Vbid&) override {
        }
    };

    CollectionsVBFlushManifestTest() {
        config.parseConfiguration({});
        checkpointConfig = std::make_unique<CheckpointConfig>(config);
        vbucket = std::make_shared<EPVBucket>(
                Vbid(0),
                vbucket_state_active,
                stats,
                *checkpointConfig,
                /*kvshard*/ nullptr,
                /*lastSeqno*/ 0,
                /*lastSnapStart*/ 0,
                /*lastSnapEnd*/ 0,
                /*table*/ nullptr,
                std::make_shared<DummyCB>(),
                NoopSyncWriteCompleteCb,
                NoopSyncWriteTimeoutFactory,
                NoopSeqnoAckCb,
                config,
                EvictionPolicy::Value,
                std::make_unique<Collections::VB::Manifest>(
                        std::make_shared<Collections::Manager>()),
                CreateVbucketMethod::SetVbucket);
    }

    /**
     * Update the manifest and record all of the resulting system events
     * in the current batch.
     */
    void updateAndRecord(const CollectionsManifest& cm) {
        manifest.update(
                std::shared_lock<folly::SharedMutex>(vbucket->getStateLock()),
                *vbucket,
                makeManifest(cm));
        std::vector<queued_item> items;
        vbucket->checkpointManager->getNextItemsForPersistence(items);
        for (const auto& item : items) {
            if (item->getOperation() == queue_op::system_event) {
                flush->recordSystemEvent(*item);
            }
        }
    }

    EPStats stats;
    Configuration config;
    std::unique_ptr<CheckpointConfig> checkpointConfig;
    VBucketPtr vbucket;
};

// A dropped collection which never had items is omitted from the dropped list,
// there is nothing for compaction to purge.
TEST_F(CollectionsVBFlushManifestTest, emptyDroppedCollectionNotEncoded) {
    CollectionsManifest cm;
    cm.add(CollectionEntry::fruit);
    updateAndRecord(cm);
    cm.remove(CollectionEntry::fruit);
    updateAndRecord(cm);
    commit();

    // Expects fruit gone and the dropped list never written
    expectDisk({.manifestUid = ManifestUid{cm.getUid()},
                .collections = OpenCollections{defaultCollection}});
}
